//
// Q: How do derived query methods work?
// A: Spring Data JPA parses the method name into a query. findByNameAndPrice
//    becomes SELECT * FROM products WHERE name = ? AND price = ?. No 
//    implementation needed — Spring auto-generates it.
//
// Q: JPQL vs Native SQL?
// A: JPQL uses entity/field names (portable across databases).
//    Native SQL uses table/column names (database-specific).
//    Use JPQL by default; native SQL for complex queries (CTEs, window functions).
//
// Q: What is @Modifying?
// A: Required for UPDATE/DELETE queries with @Query. Without it, Spring
//    expects a SELECT query. Use clearAutomatically=true to avoid stale cache.
//
// Q: What are Specifications?
// A: A pattern for building dynamic queries programmatically. Each Specification
//    represents one filter criterion. They're composable with AND/OR.
//    Think of it as a query builder — similar to TypeORM's QueryBuilder.
//
// Q: What are projections?
// A: Selecting specific columns instead of the entire entity. Reduces data
//    transfer and avoids loading unnecessary fields. Interface-based or
//    class-based (constructor expression).

