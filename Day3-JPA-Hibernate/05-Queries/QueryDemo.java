// =========================================================================
// 6. SPECIFICATIONS — Dynamic query building
// =========================================================================
// Use when you need to build queries dynamically based on filter criteria
// (like a search form with optional fields).

// Repository must extend JpaSpecificationExecutor
interface ProductSpecRepository extends 
    JpaRepository<Product, Long>, 
    JpaSpecificationExecutor<Product> {
}

// Specification definitions
class ProductSpecs {
    
    public static Specification<Product> hasCategory(String category) {
        return (root, query, cb) -> 
            category == null ? null : cb.equal(root.get("category"), category);
    }

    public static Specification<Product> priceBetween(Double min, Double max) {
        return (root, query, cb) -> {
            if (min != null && max != null) {
                return cb.between(root.get("price"), min, max);
            } else if (min != null) {
                return cb.greaterThanOrEqualTo(root.get("price"), min);
            } else if (max != null) {
                return cb.lessThanOrEqualTo(root.get("price"), max);
            }
            return null;
        };
    }

    public static Specification<Product> nameContains(String keyword) {
        return (root, query, cb) ->
            keyword == null ? null : cb.like(cb.lower(root.get("name")), 
                "%" + keyword.toLowerCase() + "%");
    }

    public static Specification<Product> isActive() {
        return (root, query, cb) -> cb.isTrue(root.get("active"));
    }
}

